M = 120; EY = 100; H1 = 200; L2Y = 332

def eyebrow(t): return T(M, EY, t, size=17, fill=C["faint"], weight=600, ls="3")
def h1(lines, y=H1, size=52): return TL(M, y, lines, size=size, lh=1.36, weight=700, fill=C["ink"])
def body(lines, y=L2Y, size=22, fill=None): return TL(M, y, lines, size=size, lh=1.7, fill=fill or C["ink2"])
def foot(t, y=846, fill=None): return T(M, y, t, size=15, fill=fill or C["faint"])

def card(x,y,w,h,label,lines):
    return "\n".join([R(x,y,w,h,fill=C["wash"],stroke=C["line"],rx=10),
        T(x+28,y+40,label,size=15,fill=C["mute"],weight=700,ls="2.4"),
        TL(x+28,y+78,lines,size=18,lh=1.62,fill=C["ink2"])])

def block(x,y,title,lines,color=None,ts=20,bs=17):
    return "\n".join([R(x,y,3,26+len(lines)*30,fill=color or C["line"]),
        T(x+20,y+20,title,size=ts,weight=700,fill=C["ink"]),
        TL(x+20,y+54,lines,size=bs,lh=1.62,fill=C["mute"])])

def meta(x,y,val,label,fill=None):
    return T(x,y,val,size=19,weight=700,fill=fill or C["ink"]) + \
           T(x,y+30,label,size=14,fill=C["faint"],ls="2")

