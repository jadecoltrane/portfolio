def card(x,y,w,h,label,lines,accent=False):
    o=[R(x,y,w,h,fill=C["accw"] if accent else C["wash"],
         stroke=C["acc"] if accent else C["line"], rx=10, sw=1.4 if accent else 1)]
    o.append(T(x+26,y+38,label,size=15,fill=C["acc"] if accent else C["mute"],weight=700,ls="2.4"))
    o.append(TL(x+26,y+76,lines,size=18,lh=1.62,fill=C["ink"] if accent else C["ink2"]))
    return "\n".join(o)

def item(x,y,w,title,lines,color=None):
    col=color or C["line"]
    o=[R(x,y,3,20+len(lines)*30,fill=col)]
    o.append(T(x+18,y+18,title,size=19,weight=700,fill=C["ink"]))
    o.append(TL(x+18,y+48,lines,size=17,lh=1.6,fill=C["mute"]))
    return "\n".join(o)

