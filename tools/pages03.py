def rowtable(x, y, w, cols, rows, head=True, rh=None, fs=16, gap=18):
    """简单表格：cols=[(标题, 宽, 颜色|None)]，rows=[[行文本 或 [多行]]]"""
    out, cy = [], y
    if head:
        cx = x
        for t, cw, _ in cols:
            out.append(T(cx, cy, t, size=14, fill=C["faint"], weight=700, ls="2"))
            cx += cw
        cy += 16
        out.append(LN(x, cy, x+w, cy))
        cy += gap
    for r in rows:
        cx, hmax = x, 0
        for (t, cw, col), cell in zip(cols, r):
            lines = cell if isinstance(cell, list) else [cell]
            if isinstance(col, tuple):
                # 首行压暗、其余正常：被排除的方案压暗，理由跟「采用」同重
                first, rest = col
                out.append(TL(cx, cy+18, lines[:1], size=fs, lh=1.56, fill=first))
                if len(lines) > 1:
                    out.append(TL(cx, cy+18+int(fs*1.56), lines[1:],
                                  size=fs, lh=1.56, fill=rest))
            else:
                out.append(TL(cx, cy+18, lines, size=fs, lh=1.56,
                              fill=col or C["ink2"], weight=700 if col == C["ink"] else 400))
            hmax = max(hmax, len(lines))
            cx += cw
        cy += 18 + hmax * int(fs*1.56) + (rh or 16)
        out.append(LN(x, cy-10, x+w, cy-10, stroke=C["line"]))
    return "".join(out), cy

