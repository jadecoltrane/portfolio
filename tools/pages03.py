def eyebrow(t): return T(M, EY, t, size=17, fill=C["faint"], weight=600, ls="3")
def h1(lines, y=H1, size=52): return TL(M, y, lines, size=size, lh=1.36, weight=700, fill=C["ink"])
def body(lines, y=L2Y, size=22, fill=None): return TL(M, y, lines, size=size, lh=1.7, fill=fill or C["ink2"])
def foot(t, y=846, fill=None): return T(M, y, t, size=15, fill=fill or C["faint"])

def card(x, y, w, h, label, lines):
    return "\n".join([R(x, y, w, h, fill=C["wash"], stroke=C["line"], rx=10),
        T(x+28, y+40, label, size=15, fill=C["mute"], weight=700, ls="2.4"),
        TL(x+28, y+78, lines, size=18, lh=1.62, fill=C["ink2"])])

def meta(x, y, val, label, fill=None):
    return T(x, y, val, size=18, weight=700, fill=fill or C["ink"]) + \
           T(x, y+28, label, size=14, fill=C["faint"], ls="2")

def rowtable(x, y, w, cols, rows, head=True, rh=None, fs=16, gap=18):
    """简单表格：cols=[(标题, 宽, 颜色|None)]，rows=[[行文本 或 [多行]]]"""
    out, cy = [], y
    if head:
        cx = x
        for t, cw, _ in cols:
            out.append(T(cx, cy, t, size=14, fill=C["faint"], weight=700, ls="2"))
            cx += cw
        cy += 16
        out.append(LN(x, cy, x+w, cy))
        cy += gap
    for r in rows:
        cx, hmax = x, 0
        for (t, cw, col), cell in zip(cols, r):
            lines = cell if isinstance(cell, list) else [cell]
            out.append(TL(cx, cy+18, lines, size=fs, lh=1.56,
                          fill=col or C["ink2"], weight=700 if col == C["ink"] else 400))
            hmax = max(hmax, len(lines))
            cx += cw
        cy += 18 + hmax * int(fs*1.56) + (rh or 16)
        out.append(LN(x, cy-10, x+w, cy-10, stroke=C["line"]))
    return "".join(out), cy

